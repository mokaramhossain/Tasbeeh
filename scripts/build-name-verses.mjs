#!/usr/bin/env node
/**
 * The verse shown under each name: its Arabic, and two published translations.
 *
 * Sources, all from the fawazahmed0/quran-api dataset:
 *   Arabic   Tanzil "simple" — the same text the app downloads surahs in.
 *   English  Sahih International (Umm Muhammad), via Tanzil — the same
 *            translation the app downloads surahs with.
 *   Bangla   Dr. Abu Bakr Muhammad Zakaria, as published by the King Fahd
 *            Complex (qurancomplex.gov.sa).
 *
 * Two things are changed, and nothing else:
 *
 *   1. The bismillah is taken off verse 1. The dataset prints it at the head of
 *      the first verse of every surah but al-Fatiha, so 112:1 would otherwise
 *      read "بِسْمِ ٱللَّهِ ... قُلْ هُوَ ٱللَّهُ أَحَدٌ" as if it were one verse.
 *   2. Zakaria's footnote markers ([১], [২]) are removed. They point into his
 *      tafsir notes, which are not in the dataset, so they would point at
 *      nothing. Every word of the translation is kept as published.
 *
 * Verses are shown whole. A long one (2:255, 24:35) is not shortened: an
 * ellipsis in scripture means the text was cut to fit, which the content tests
 * refuse.
 *
 * Also writes docs/name-verses.csv, one row per verse, for review.
 *
 * Run: npm run data:name-verses
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { NAMES } from './names.mjs';
import { findName } from './name-match.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RAW = 'https://raw.githubusercontent.com/fawazahmed0/quran-api/1/editions';
const EDITIONS = { arabic: 'ara-quransimple', en: 'eng-ummmuhammad', bn: 'ben-abubakrzakaria' };
const MARKER = '\\s*\\[[০-৯0-9]+\\]';
/** Remove a footnote marker, and the space it leaves before punctuation. */
const dropFootnotes = (text) =>
  text.replace(new RegExp(`${MARKER}\\s*(?=[,।;:!?])`, 'g'), '').replace(new RegExp(MARKER, 'g'), '');

const load = async (edition) => {
  const response = await fetch(`${RAW}/${edition}.json`);
  if (!response.ok) throw new Error(`${edition}: ${response.status}`);
  const { quran } = await response.json();
  return new Map(quran.map((v) => [`${v.chapter}:${v.verse}`, v]));
};

const [arabic, en, bn] = await Promise.all([EDITIONS.arabic, EDITIONS.en, EDITIONS.bn].map(load));

const clean = (text) => text.replace(/\s+/g, ' ').trim();

// The dataset's own 1:1, so the prefix is compared byte for byte with itself.
const BISMILLAH = `${clean(arabic.get('1:1').text)} `;

const verseText = (ref) => {
  const { chapter, verse, text } = arabic.get(ref);
  if (verse === 1 && chapter !== 1 && text.startsWith(BISMILLAH)) return clean(text.slice(BISMILLAH.length));
  return clean(text);
};

const refs = [...new Set(NAMES.map((row) => row[5]).filter(Boolean))];
const verses = {};
for (const ref of refs) {
  if (!arabic.has(ref) || !en.has(ref) || !bn.has(ref)) throw new Error(`${ref} is missing from a source`);
  verses[ref] = {
    arabic: verseText(ref),
    meaning: { en: clean(en.get(ref).text), bn: clean(dropFootnotes(bn.get(ref).text)) }
  };
}

const pad = (n) => String(n).padStart(3, '0');
const highlight = {};
NAMES.forEach(([name, trn, , , , ref], i) => {
  if (!ref) return;
  const at = findName(name, verses[ref].arabic);
  if (!at) throw new Error(`${trn} not found in ${ref}`);
  highlight[`asma_${pad(i + 1)}`] = at;
});

const file = `/**
 * The verse under each name: the Arabic, and two published translations.
 *
 * Arabic: Tanzil (simple). English: Sahih International. Bangla: Dr. Abu Bakr
 * Muhammad Zakaria (King Fahd Complex). The bismillah is taken off verse 1 and
 * Zakaria's footnote markers are removed; nothing else is changed. See
 * scripts/build-name-verses.mjs for why.
 *
 * \`NAME_HIGHLIGHT\` is where the name sits in its verse, as [first, last]
 * indexes into \`arabic.split(' ')\`.
 *
 * Generated by scripts/build-name-verses.mjs — edit that, not this.
 */
export interface NameVerse {
  arabic: string;
  meaning: { en: string; bn: string };
}

export const VERSE_TRANSLATORS = {
  en: 'Sahih International',
  bn: 'ড. আবু বকর মুহাম্মাদ যাকারিয়া'
};

export const NAME_VERSES: Record<string, NameVerse> = ${JSON.stringify(verses, null, 2)};

export const NAME_HIGHLIGHT: Record<string, [number, number]> = ${JSON.stringify(highlight)};
`;
writeFileSync(join(ROOT, 'src/data/nameVerses.generated.ts'), file);

const csv = (s) => `"${String(s).replace(/"/g, '""')}"`;
const namesAt = (ref) =>
  NAMES.filter((row) => row[5] === ref)
    .map((row) => row[1])
    .join('; ');
const rows = [
  ['ref', 'names', 'arabic', 'english', 'bangla'],
  ...refs.map((ref) => [ref, namesAt(ref), verses[ref].arabic, verses[ref].meaning.en, verses[ref].meaning.bn])
];
writeFileSync(join(ROOT, 'docs/name-verses.csv'), `﻿${rows.map((row) => row.map(csv).join(',')).join('\n')}\n`);

console.log(`wrote ${refs.length} verses for ${Object.keys(highlight).length} names`);
